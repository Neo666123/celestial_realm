    def process_blueprints(self):
        files = self.bp_listbox.get(0, tk.END)
        out_dir = self.bp_out_entry.get().strip()
        if not files or not out_dir:
            messagebox.showwarning("提示", "请选择蓝图 PNG 文件及输出目录！")
            return

        groups = {}
        for path in files:
            fname = os.path.basename(path)
            stem, _ = os.path.splitext(fname)
            m = re.match(r"^(?P<base>.+?)_(?P<layer>ground|prefab|perfab)$", stem, re.IGNORECASE)
            if m:
                base = m.group("base")
                layer_type = m.group("layer").lower()
                if layer_type == "perfab":
                    layer_type = "prefab"
                groups.setdefault(base, {})[layer_type] = path
            else:
                self.log(self.bp_log, f"[跳过] 无法识别的蓝图后缀: {fname} (请以 _ground 或 _prefab 结尾)")

        for base_name, layers in groups.items():
            try:
                layers_data = {}
                common_w, common_h = None, None

                for l_type, l_path in layers.items():
                    img = Image.open(l_path).convert("RGBA")
                    w, h, pal_str, rle_str, p_cnt = encode_image_layer(img)
                    if common_w is None:
                        common_w, common_h = w, h
                    elif (common_w, common_h) != (w, h):
                        raise ValueError(f"蓝图图层尺寸不一致: {base_name} ({common_w}x{common_h} vs {w}x{h})")
                    layers_data[l_type] = (pal_str, rle_str)

                out_filename = f"bp_{base_name}_data.lua"
                out_path = os.path.join(out_dir, out_filename)
                lua_src = build_blueprint_lua(common_w, common_h, layers_data)

                with open(out_path, "w", encoding="utf-8") as f:
                    f.write(lua_src)

                self.log(self.bp_log, f"[成功打包蓝图] {out_filename} (包含图层: {', '.join(layers.keys())})")
            except Exception as e:
                self.log(self.bp_log, f"[错误] 蓝图 {base_name} 打包失败: {e}")

        messagebox.showinfo("完成", "蓝图打包处理完毕！")

